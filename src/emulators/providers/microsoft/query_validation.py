def paths(node: Any, bound: frozenset[str] = frozenset()) -> list[str]:
    if isinstance(node, Path):
        return [] if node.segments[0] in bound else [node.segments[0]]
    if isinstance(node, Lambda):
        return paths(node.source, bound) + paths(node.body, bound | {node.var})
    if isinstance(node, (tuple, list)):
        return [name for item in node for name in paths(item, bound)]
    if is_dataclass(node):
        return [name for field in fields(node) for name in paths(getattr(node, field.name), bound)]
    return []


def validate(options: QueryOptions, context: str) -> None:
    entity = context.split("/", 1)[0]
    allowed = PROPERTIES.get(entity)
    if allowed is None:
        return
    names = [name.split("/", 1)[0] for name in options.select or []]
    if options.filter:
        names.extend(paths(parse_filter(options.filter)))
    if options.orderby:
        names.extend(paths(parse_orderby(options.orderby)))
    for name in names:
        if name not in allowed and name != "*" and not name.startswith(("@", "extension_")):
            from emulators.providers.microsoft.common import graph_error

            raise graph_error(
                400,
                "BadRequest",
                f"Could not find a property named '{name}' on type 'microsoft.graph.{entity.rstrip('s')}'.",
            )

"""Validate wire arguments before mutations, using a snapshot of Dropbox's Stone types.

The catalog is generated by the dev-only ``generate_argument_schema.py`` test utility.
Keeping it as JSON avoids a runtime SDK dependency while validating nested list items,
union payloads, omitted required fields and vendor length/range constraints consistently.
"""

from __future__ import annotations

import json
import math
import re
from datetime import datetime
from functools import lru_cache
from pathlib import Path
from typing import Any

from emulators.providers.dropbox.common import Args, BadInput


@lru_cache(maxsize=1)
def catalog() -> dict[str, Any]:
    return json.loads(Path(__file__).with_name("argument_schema.json").read_text(encoding="utf-8"))


def validate_argument(route: str, args: Args) -> None:
    data = catalog()
    schema = data["routes"].get(route)
    if schema is not None and schema.get("type") != "void":
        validate(schema, args.data, args.where, data["definitions"])


def validate(schema: dict[str, Any], value: Any, where: str, definitions: dict[str, Any]) -> None:
    if "ref" in schema:
        schema = definitions[schema["ref"]]
    kind = schema["type"]

    def fail(message: str) -> None:
        raise BadInput(f"{where}: {message}")

    if kind == "nullable":
        if value is not None:
            validate(schema["item"], value, where, definitions)
    elif kind == "struct":
        if not isinstance(value, dict):
            fail("expected object")
        for name in schema["required"]:
            if value.get(name) is None:
                fail(f"{name}: missing required field")
        for name, child in schema["fields"].items():
            if name in value and value[name] is not None:
                validate(child, value[name], f"{where}: {name}", definitions)
    elif kind == "union":
        name = value if isinstance(value, str) else value.get(".tag") if isinstance(value, dict) else None
        if not isinstance(name, str) or name not in schema["tags"]:
            fail("expected union with a valid '.tag'")
        child = schema["tags"][name]
        resolved = definitions[child["ref"]] if "ref" in child else child
        if resolved["type"] == "void":
            return
        # Stone inlines a struct payload next to .tag, but nests other payloads under the tag.
        payload = (
            value if resolved["type"] == "struct" else value.get(name) if isinstance(value, dict) else None
        )
        validate(child, payload, f"{where}: {name}", definitions)
    elif kind == "list":
        if not isinstance(value, list):
            fail("expected list")
        bounds(schema, len(value), fail)
        for index, item in enumerate(value):
            validate(schema["item"], item, f"{where}[{index}]", definitions)
    elif kind in ("string", "timestamp"):
        if not isinstance(value, str):
            fail("expected string")
        try:
            value.encode("utf-8")
        except UnicodeError:
            fail("expected valid Unicode")
        if kind == "timestamp":
            try:
                datetime.strptime(value, schema["format"])
            except ValueError:
                fail("invalid timestamp format")
        else:
            bounds(schema, len(value), fail)
            if schema.get("pattern") and re.fullmatch(schema["pattern"], value) is None:
                fail("value did not match pattern '" + schema["pattern"] + "'")
    elif kind == "boolean":
        if not isinstance(value, bool):
            fail("expected boolean")
    elif kind in ("integer", "float"):
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            fail("expected " + kind)
        if kind == "integer" and not isinstance(value, int):
            fail("expected integer")
        if isinstance(value, float) and (
            not math.isfinite(value) or (kind == "integer" and not value.is_integer())
        ):
            fail("expected finite " + kind)
        bounds(schema, value, fail)
    elif kind == "void" and value is not None:
        fail("expected null")


def bounds(schema: dict[str, Any], value: int | float, fail: Any) -> None:
    if schema.get("min") is not None and value < schema["min"]:
        fail(f"value is too small; minimum is {schema['min']}")
    if schema.get("max") is not None and value > schema["max"]:
        fail(f"value is too large; maximum is {schema['max']}")

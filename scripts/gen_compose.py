"""Regenerate docker-compose.yml (and its build override) so every vendor hostname is a network alias.

``docker-compose.yml`` runs the published image pinned to the project version; it is the file consumers
download from a release. ``docker-compose.override.yml``, which ``docker compose`` merges automatically in
this repo, builds the image from source instead.

Run after adding a provider or a hostname, or bumping the version: ``uv run python scripts/gen_compose.py``.
CI runs it with ``--check`` to catch a stale file.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

from emulators.core.hub import discover_providers
from emulators.core.tls import concrete_hosts

ROOT = Path(__file__).resolve().parents[1]
IMAGE = "ghcr.io/k-sandhu/emulators"

COMPOSE = """\
# Generated by scripts/gen_compose.py — do not edit by hand.
#
# Runs the published image (linux/amd64, linux/arm64) pinned to this release; set EMULATORS_IMAGE to run
# another tag. Inside a checkout of the repo, `docker compose` also merges docker-compose.override.yml and
# builds from source; pass `-f docker-compose.yml` to run the published image there.
#
# Other compose projects reach the emulators under the vendors' real hostnames by joining the
# external network `emulators-vendors` and trusting the CA in the `emulators-certs` volume.
# See docs/howto/docker-compose.md.
name: emulators

services:
  emulators:
    image: ${EMULATORS_IMAGE:-{image}}
    environment:
      EMULATORS_PORT: "80"
      EMULATORS_HTTPS_PORT: "443"
      EMULATORS_PROVIDERS: ${EMULATORS_PROVIDERS:-}
      EMULATORS_ANCHOR: ${EMULATORS_ANCHOR:-}
      EMULATORS_SEED: ${EMULATORS_SEED:-emulators}
      EMULATORS_WEBHOOK_MODE: ${EMULATORS_WEBHOOK_MODE:-async}
    # Bind 80/443 as the non-root user.
    sysctls:
      net.ipv4.ip_unprivileged_port_start: 0
    ports:
      - "${EMULATORS_HTTP_HOST_PORT:-44080}:80"
      - "${EMULATORS_HTTPS_HOST_PORT:-44443}:443"
{provider_ports}
    volumes:
      - certs:/certs
    healthcheck:
      test: ["CMD", "python", "-c", "import urllib.request; urllib.request.urlopen('http://127.0.0.1:80/_emulator/health', timeout=3)"]
      interval: 10s
      timeout: 3s
      retries: 10
      start_period: 20s
    networks:
      vendors:
        aliases:
{aliases}

volumes:
  certs:
    name: emulators-certs

networks:
  vendors:
    name: emulators-vendors
"""

OVERRIDE = """\
# Generated by scripts/gen_compose.py — do not edit by hand.
#
# `docker compose` merges this file automatically when it runs in this repo without `-f`, so local runs and
# CI build the image from the checkout (tagged emulators:local) instead of pulling the published release.
services:
  emulators:
    build: .
    image: emulators:local
"""


def render() -> dict[Path, str]:
    with (ROOT / "pyproject.toml").open("rb") as f:
        version = tomllib.load(f)["project"]["version"]
    providers = discover_providers()
    hosts = concrete_hosts(sorted({h for p in providers.values() for h in p.hosts}))
    ports = sorted(p.default_port for p in providers.values() if p.default_port)
    compose = (
        COMPOSE.replace("{image}", f"{IMAGE}:v{version}")
        .replace("{provider_ports}", "\n".join(f'      - "{port}:{port}"' for port in ports))
        .replace("{aliases}", "\n".join(f"          - {host}" for host in hosts))
    )
    return {ROOT / "docker-compose.yml": compose, ROOT / "docker-compose.override.yml": OVERRIDE}


def main() -> int:
    parser = argparse.ArgumentParser(description="Regenerate docker-compose.yml and its build override.")
    parser.add_argument("--check", action="store_true", help="exit 1 if a file is stale instead of writing")
    args = parser.parse_args()
    files = render()
    if args.check:
        stale = [
            p.name for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        if stale:
            print(f"stale: {', '.join(stale)}; run `uv run python scripts/gen_compose.py`", file=sys.stderr)
            return 1
        return 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {', '.join(p.name for p in files)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
